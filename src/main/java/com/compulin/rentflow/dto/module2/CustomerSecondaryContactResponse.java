package com.compulin.rentflow.dto.module2;


public class CustomerSecondaryContactResponse {

    private Integer secondaryContactId;
    private Integer customerId;
    private String contactName;
    private String relationship;
    private String phoneNumber;
    private String alternatePhone;
    private String email;
    private String address;
    private String notes;

    public Integer getSecondaryContactId() {
        return secondaryContactId;
    }

    public void setSecondaryContactId(Integer secondaryContactId) {
        this.secondaryContactId = secondaryContactId;
    }

    public Integer getCustomerId() {
        return customerId;
    }

    public void setCustomerId(Integer customerId) {
        this.customerId = customerId;
    }

    public String getContactName() {
        return contactName;
    }

    public void setContactName(String contactName) {
        this.contactName = contactName;
    }

    public String getRelationship() {
        return relationship;
    }

    public void setRelationship(String relationship) {
        this.relationship = relationship;
    }

    public String getPhoneNumber() {
        return phoneNumber;
    }

    public void setPhoneNumber(String phoneNumber) {
        this.phoneNumber = phoneNumber;
    }

    public String getAlternatePhone() {
        return alternatePhone;
    }

    public void setAlternatePhone(String alternatePhone) {
        this.alternatePhone = alternatePhone;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getNotes() {
        return notes;
    }

    public void setNotes(String notes) {
        this.notes = notes;
    }
}